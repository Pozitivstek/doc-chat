def find_font() -> Path:
    for candidate in FONT_CANDIDATES:
        if candidate.exists():
            return candidate
    sys.exit("Не найден шрифт с кириллицей: укажите путь в FONT_CANDIDATES")


def main() -> None:
    pdf = FPDF()
    pdf.add_font("Body", fname=str(find_font()))
    for title, body in PAGES:
        pdf.add_page()
        pdf.set_font("Body", size=16)
        pdf.multi_cell(0, 10, title)
        pdf.ln(4)
        pdf.set_font("Body", size=12)
        pdf.multi_cell(0, 8, body)
    out = Path(__file__).resolve().parent.parent / "samples" / "dogovor-postavki.pdf"
    out.parent.mkdir(exist_ok=True)
    pdf.output(str(out))
    print(f"Готово: {out}")


if __name__ == "__main__":
    main()
